#!/usr/bin/env python3
"""One promotion project for the whole lifecycle.

Turns the tool's single-target pipeline (examples/gitlab/.gitlab-ci.yml) into
one where every job that talks to PingOne runs once per GitLab environment:

    python3 make_pipeline.py ../../gitlab/.gitlab-ci.yml dev test production > .gitlab-ci.yml

Each environment has its own environment-scoped CI/CD variables (above all
PINGONE_TARGET_ENVIRONMENT_ID and the worker credentials) and its own
protected-environment approvals. After a merge, the plan job of every
environment runs; only the one whose trusted target is the request's target
plans (for-this-environment.sh), the others stop at once. Deploy with the
manual job of that environment. The runner still checks that the request's
target is the job's trusted target, so a wrong job fails closed.

Manual rollback pipelines take
PROMOTION_GITLAB_ENVIRONMENT=<name> to choose the environment.
"""
import copy
import re
import sys

import yaml

ROUTE = "./examples/davinci-request-flow/gitlab/for-this-environment.sh"
SELECT = "source ./examples/gitlab/select-request.sh"
NAME = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_-]{0,63}$")
# Jobs whose environment is $PROMOTION_ENVIRONMENT, i.e. that touch one PingOne target.
MANUAL_WEB = {"rollback_plan", "apply_rollback"}


def tier(env):
    e = env.lower()
    for prefix, name in (("prod", "production"), ("stag", "staging"), ("test", "testing"), ("qa", "testing"),
                         ("uat", "testing"), ("dev", "development")):
        if e.startswith(prefix):
            return name
    return "other"


def per_environment(ci, envs):
    out = {}
    env_jobs = [k for k, v in ci.items() if isinstance(v, dict) and (v.get("environment") or {}).get("name") == "$PROMOTION_ENVIRONMENT"]
    if "plan_promotion" not in env_jobs or "apply_promotion" not in env_jobs:
        raise SystemExit("unexpected pipeline: plan_promotion/apply_promotion with environment $PROMOTION_ENVIRONMENT not found")
    for key, value in ci.items():
        if key not in env_jobs:
            out[key] = value
            continue
        for env in envs:
            job = copy.deepcopy(value)
            job["environment"]["name"] = env
            job["resource_group"] = f"pingone-{env}"
            if "deployment_tier" in job["environment"]:
                job["environment"]["deployment_tier"] = tier(env)
            script = list(job["script"])
            pre = [f"export PROMOTION_ENVIRONMENT=\"${{PROMOTION_ENVIRONMENT:-$CI_ENVIRONMENT_NAME}}\"",
                   'test "$PROMOTION_ENVIRONMENT" = "$CI_ENVIRONMENT_NAME" || { echo "Scope PROMOTION_ENVIRONMENT to $CI_ENVIRONMENT_NAME" >&2; exit 1; }']
            if key == "plan_promotion":
                if SELECT not in script:
                    raise SystemExit("plan_promotion no longer sources select-request.sh")
                i = script.index(SELECT) + 1
                script[i:i] = [f"source {ROUTE}", 'if [[ "$PP_FOR_THIS_ENVIRONMENT" != true ]]; then exit 0; fi']
            elif key == "apply_promotion":
                pre.append('test -f plan.json || { echo "No plan in ' + env + ': the merged request targets another environment. '
                           'Run the deploy job of the environment named in the merge request." >&2; exit 1; }')
            job["script"] = pre + script
            if "needs" in job:
                job["needs"] = [dict(n, job=f"{n['job']}_{env}") if isinstance(n, dict) and n.get("job") in env_jobs else n
                                for n in job["needs"]]
            if key in MANUAL_WEB:
                for rule in job.get("rules", []):
                    if "if" in rule:
                        rule["if"] = f"({rule['if']}) && $PROMOTION_GITLAB_ENVIRONMENT == \"{env}\""
            out[f"{key}_{env}"] = job
    variables = dict(out.get("variables") or {})
    # The environment name comes from each job's GitLab environment instead.
    variables.pop("PROMOTION_ENVIRONMENT", None)
    out["variables"] = variables
    # Jobs without an environment (validate_request) no longer have one to group by.
    out[".runner_job"] = dict(out[".runner_job"], resource_group="pingone-validate")
    return out


def main(argv):
    if len(argv) < 3:
        raise SystemExit(__doc__)
    envs = argv[2:]
    if len(set(envs)) != len(envs) or not all(NAME.match(e) for e in envs):
        raise SystemExit("environment names must be unique and match " + NAME.pattern)
    with open(argv[1]) as f:
        ci = yaml.safe_load(f)
    out = per_environment(ci, envs)
    sys.stdout.write("# Generated by examples/davinci-request-flow/gitlab/make_pipeline.py from\n"
                     "# examples/gitlab/.gitlab-ci.yml for GitLab environments: " + ", ".join(envs) + ".\n"
                     "# One promotion project for every target; see the DaVinci kit RUNBOOK.\n"
                     "# PROMOTION_TOOL_REF must be set to a reviewed full commit SHA.\n")
    yaml.safe_dump(out, sys.stdout, sort_keys=False, width=200, default_flow_style=False)


if __name__ == "__main__":
    main(sys.argv)
